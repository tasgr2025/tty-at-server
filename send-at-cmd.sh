#!/usr/bin/env bash

# send-at-cmd.sh — отправляет AT-команду в последовательный порт и выводит ответ

if [ $# -lt 2 ]; then
    echo "Использование: $0 <устройство> <команда> [скорость]"
    exit 1
fi

DEVICE="$1"
COMMAND="$2"
BAUD="${3:-115200}"

# Настраиваем порт: raw-режим, без эха, указанная скорость
stty -F "$DEVICE" raw -echo "$BAUD" || exit 1

# Открываем порт для чтения и записи (дескриптор 3)
exec 3<>"$DEVICE" || exit 1

# Отправляем команду + символ возврата каретки
printf '%s\r' "$COMMAND" >&3

# Даём модему время на ответ
sleep 0.5

# Читаем всё, что пришло за 1 секунду
timeout 1 cat <&3

# Закрываем дескриптор
exec 3>&-
exec 3<&-
